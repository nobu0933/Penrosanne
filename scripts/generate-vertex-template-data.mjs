import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildVertexExpansionTemplates } from '../src/game/TrainingVertexTemplates.js';

// Regenerate only when the structural vertex rules change. Runtime imports the
// generated coordinates and never performs the expensive closure calculation.
const templates = buildVertexExpansionTemplates(120);
const compact = Object.fromEntries(Object.entries(templates).map(([type, template]) => [type, {
  seedCount: template.seedCount,
  seedVertexIds: template.seedVertexIds,
  tiles: template.tiles.map(tile => [tile.shape, tile.centerX, tile.centerY, tile.rotation]),
}]));
const destination = fileURLToPath(new URL('../src/game/TrainingVertexTemplateData.js', import.meta.url));
writeFileSync(destination, `// Generated by scripts/generate-vertex-template-data.mjs; do not edit manually.\nexport const VERTEX_TEMPLATE_DATA = ${JSON.stringify(compact)};\n`);
console.log(`Saved ${Object.keys(compact).length} vertex templates.`);
